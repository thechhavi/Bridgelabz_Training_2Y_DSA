public class swap {
    public static void main(String[] args) {
        int a=10;
        int b=5;
        int temp;
        temp=a;
        a=b;
        b=temp;
        System.out.println("before swap a= 10");
        System.out.println("before swap b= 5");
        System.out.println("after swap a="+a);
        System.out.println("after swap b="+b);

    }
    
}